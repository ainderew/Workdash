export type PlatformType = "youtube" | "twitter" | "github" | "instagram" | "facebook" | "generic";

const PLATFORM_ICON_MAP: Record<PlatformType, React.ComponentType<{ size?: number }>> = {
    youtube: YouTubeIcon,
    twitter: XIcon,
    github: GitHubIcon,
    instagram: InstagramIcon,
    facebook: FacebookIcon,
    generic: GlobeIcon,
};

const PLATFORM_GRADIENT_MAP: Record<PlatformType, string> = {
    youtube: "from-red-900/60 to-red-950/80",
    twitter: "from-sky-900/60 to-sky-950/80",
    github: "from-neutral-700/60 to-neutral-900/80",
    instagram: "from-purple-900/60 to-pink-950/80",
    facebook: "from-blue-900/60 to-blue-950/80",
    generic: "from-neutral-700/60 to-neutral-800/80",
};

export function getPlatformIcon(platform: PlatformType) {
    return PLATFORM_ICON_MAP[platform];
}

export function getPlatformGradient(platform: PlatformType) {
    return PLATFORM_GRADIENT_MAP[platform];
}
